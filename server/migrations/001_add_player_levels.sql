ALTER TABLE players
  ADD COLUMN IF NOT EXISTS level INTEGER NOT NULL DEFAULT 1,
  ADD COLUMN IF NOT EXISTS exp INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS "expToNext" INTEGER NOT NULL DEFAULT 100,
  ADD COLUMN IF NOT EXISTS damage INTEGER NOT NULL DEFAULT 18,
  ADD COLUMN IF NOT EXISTS skills JSONB NOT NULL DEFAULT '[]';

UPDATE players
SET "expToNext" = 100 + GREATEST(level - 1, 0) * 60,
    "maxHealth" = 100 + GREATEST(level - 1, 0) * 8,
    damage = 18 + GREATEST(level - 1, 0) * 2
WHERE TRUE;
